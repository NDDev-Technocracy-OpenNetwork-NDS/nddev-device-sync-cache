//! Native BuildKit mirror configuration. Producing it does not bind or restart a daemon.
use crate::binding::Base;

pub const REGISTRIES: [&str; 4] = ["docker.io", "ghcr.io", "gcr.io", "cgr.dev"];

/// Keep canonical FROM references while selecting the existing namespaced OCI routes.
/// Plain HTTP is enabled only for the literal loopback mirror, never for an origin.
/// BuildKit retains its native origin fallback; central-only operation additionally
/// requires the owning executor's qualified egress policy.
pub fn buildkit_config(base: &Base) -> String {
    let host = format!("127.0.0.1:{}", base.port());
    let mut result = String::from("# Generated by nds-cache; anonymous public images only.\n");
    for registry in REGISTRIES {
        result.push_str(&format!(
            "[registry.\"{registry}\"]\n  mirrors = [\"{host}/{registry}\"]\n"
        ));
    }
    result.push_str(&format!("[registry.\"{host}\"]\n  http = true\n"));
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_native_toml_preserves_origins_and_restricts_http_to_loopback() {
        let value: toml::Value =
            toml::from_str(&buildkit_config(&Base::new(18740).unwrap())).unwrap();
        let registries = value["registry"].as_table().unwrap();
        assert_eq!(registries.len(), REGISTRIES.len() + 1);
        for registry in REGISTRIES {
            let entry = &registries[registry];
            assert_eq!(
                entry["mirrors"][0].as_str().unwrap(),
                format!("127.0.0.1:18740/{registry}")
            );
            assert!(entry.get("http").is_none());
            assert!(entry.get("insecure").is_none());
        }
        assert_eq!(registries["127.0.0.1:18740"]["http"].as_bool(), Some(true));
        let contract: serde_json::Value =
            serde_json::from_str(include_str!("../../../contracts/clients.json")).unwrap();
        let declared: Vec<_> = contract["routes"]
            .as_array()
            .unwrap()
            .iter()
            .filter_map(|route| route["prefix"].as_str()?.strip_prefix("/v2/"))
            .collect();
        assert_eq!(declared, REGISTRIES);
    }
}
