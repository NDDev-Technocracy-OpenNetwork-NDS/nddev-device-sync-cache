#![cfg(any(target_os = "linux", target_os = "macos"))]
use nddev_device_sync_cache_client::{
    CancellationToken,
    binding::Base,
    pub_get::{self, Error, Options},
};
use sha2::{Digest, Sha256};
use std::{
    fs,
    io::{Read, Write},
    net::TcpListener,
    os::unix::fs::PermissionsExt,
    path::PathBuf,
    thread,
    time::Duration,
};

fn hash(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}
fn spec() -> String {
    "name: fixture\nenvironment:\n  sdk: '>=3.4.0 <4.0.0'\ndependencies:\n  collection: 1.19.1\n"
        .into()
}
fn lock(sha: &str) -> String {
    format!(
        "# Generated by pub\npackages:\n  collection:\n    dependency: 'direct main'\n    description:\n      name: collection\n      sha256: '{sha}'\n      url: https://pub.dev\n    source: hosted\n    version: '1.19.1'\nsdks:\n  dart: '>=3.4.0 <4.0.0'\n"
    )
}
fn quote(path: &std::path::Path) -> String {
    format!("'{}'", path.to_str().unwrap().replace('\'', "'\\''"))
}
fn fixture(port: u16, sha: &str, script: &str) -> (tempfile::TempDir, Options, PathBuf) {
    let root = tempfile::tempdir().unwrap();
    fs::set_permissions(root.path(), fs::Permissions::from_mode(0o700)).unwrap();
    fs::write(root.path().join("pubspec.yaml"), spec()).unwrap();
    fs::write(root.path().join("pubspec.lock"), lock(sha)).unwrap();
    let dart = root.path().join("dart");
    let log = root.path().join("native.log");
    fs::write(
        &dart,
        format!(
            "#!/bin/sh\nprintf '%s\\n' \"$*\" >> {}\n{script}\n",
            quote(&log)
        ),
    )
    .unwrap();
    fs::set_permissions(&dart, fs::Permissions::from_mode(0o700)).unwrap();
    let options = Options {
        base: Base::new(port).unwrap(),
        project: fs::canonicalize(root.path()).unwrap(),
        cache: fs::canonicalize(root.path()).unwrap().join("fresh-cache"),
        dart,
    };
    (root, options, log)
}
fn server(body: Vec<u8>, status: u16) -> (u16, thread::JoinHandle<String>) {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let port = listener.local_addr().unwrap().port();
    let handle = thread::spawn(move || {
        listener.set_nonblocking(true).unwrap();
        let start = std::time::Instant::now();
        let mut stream = loop {
            match listener.accept() {
                Ok((s, _)) => break s,
                Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                    assert!(start.elapsed() < Duration::from_secs(5));
                    thread::sleep(Duration::from_millis(5));
                }
                Err(e) => panic!("{e}"),
            }
        };
        stream
            .set_read_timeout(Some(Duration::from_secs(2)))
            .unwrap();
        let mut request = Vec::new();
        let mut byte = [0_u8; 1];
        while !request.ends_with(b"\r\n\r\n") {
            assert!(request.len() < 8192);
            stream.read_exact(&mut byte).unwrap();
            request.push(byte[0]);
        }
        write!(
            stream,
            "HTTP/1.1 {status} Test\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            body.len()
        )
        .unwrap();
        stream.write_all(&body).unwrap();
        String::from_utf8(request).unwrap()
    });
    (port, handle)
}
#[tokio::test]
async fn wrong_digest_never_preloads_or_creates_a_cache() {
    let (port, server) = server(b"not the locked archive".to_vec(), 200);
    let (root, options, log) = fixture(port, &"0".repeat(64), "exit 91");
    assert_eq!(
        pub_get::run(&options, CancellationToken::new())
            .await
            .unwrap_err(),
        Error::Digest
    );
    assert!(!options.cache.exists() && !log.exists());
    assert_eq!(
        fs::read_to_string(root.path().join("pubspec.lock")).unwrap(),
        lock(&"0".repeat(64))
    );
    let request = server.join().unwrap();
    assert!(request.starts_with("GET /pub/api/archives/collection-1.19.1.tar.gz "));
    assert!(
        !request.to_lowercase().contains("authorization:")
            && !request.to_lowercase().contains("cookie:")
    );
}
