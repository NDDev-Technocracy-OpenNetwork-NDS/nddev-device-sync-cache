#[tokio::test]
async fn private_or_override_scope_refuses_before_a_socket_or_native_process() {
    for private in [true, false] {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        listener.set_nonblocking(true).unwrap();
        let (root, options, log) = fixture(
            listener.local_addr().unwrap().port(),
            &"0".repeat(64),
            "exit 91",
        );
        if private {
            fs::write(
                root.path().join("pubspec.lock"),
                lock(&"0".repeat(64)).replace("https://pub.dev", "https://private.invalid"),
            )
            .unwrap();
        } else {
            fs::write(
                root.path().join("pubspec_overrides.yaml"),
                "dependency_overrides: {}\n",
            )
            .unwrap();
        }
        let result = tokio::time::timeout(
            Duration::from_secs(2),
            pub_get::run(&options, CancellationToken::new()),
        )
        .await
        .unwrap();
        assert_eq!(result.unwrap_err(), Error::Unqualified);
        assert!(!log.exists() && !options.cache.exists());
        assert_eq!(
            listener.accept().unwrap_err().kind(),
            std::io::ErrorKind::WouldBlock
        );
    }
}
#[tokio::test]
async fn existing_cache_can_only_take_the_native_offline_warm_path() {
    for success in [true, false] {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        listener.set_nonblocking(true).unwrap();
        let (_root, options, log) = fixture(
            listener.local_addr().unwrap().port(),
            &"0".repeat(64),
            if success { "exit 0" } else { "exit 1" },
        );
        fs::create_dir(&options.cache).unwrap();
        fs::set_permissions(&options.cache, fs::Permissions::from_mode(0o700)).unwrap();
        fs::write(options.cache.join("keep"), b"existing caller data").unwrap();
        let result = pub_get::run(&options, CancellationToken::new()).await;
        if success {
            let result = result.unwrap();
            assert_eq!(result.status, "warm_offline");
            assert_eq!(result.downloaded_bytes, 0);
            assert!(!result.cache_created);
        } else {
            assert_eq!(result.unwrap_err(), Error::FreshCacheRequired);
        }
        assert_eq!(
            fs::read(options.cache.join("keep")).unwrap(),
            b"existing caller data"
        );
        assert_eq!(
            fs::read_to_string(log).unwrap(),
            "pub get --offline --enforce-lockfile\n"
        );
        assert_eq!(
            listener.accept().unwrap_err().kind(),
            std::io::ErrorKind::WouldBlock
        );
    }
}
#[tokio::test]
async fn checked_download_invokes_only_native_preload_then_original_enforced_get() {
    // This test verifies the process boundary. Actual Dart archive semantics are qualified separately.
    let body = b"checked process fixture".to_vec();
    let sha = hash(&body);
    let (port, server) = server(body.clone(), 200);
    let (_root, options, log) = fixture(port, &sha, "exit 0");
    let result = pub_get::run(&options, CancellationToken::new())
        .await
        .unwrap();
    assert_eq!(result.status, "prepared_offline");
    assert_eq!(result.archives, 1);
    assert_eq!(result.downloaded_bytes, body.len() as u64);
    assert_eq!(
        fs::metadata(&options.cache).unwrap().permissions().mode() & 0o777,
        0o700
    );
    let calls = fs::read_to_string(log).unwrap();
    let calls: Vec<_> = calls.lines().collect();
    assert_eq!(calls.len(), 2);
    assert!(calls[0].starts_with("pub cache preload "));
    assert_eq!(calls[1], "pub get --offline --enforce-lockfile");
    server.join().unwrap();
}
#[tokio::test]
async fn cancellation_reaps_the_selected_native_operation() {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let (_root, options, log) = fixture(
        listener.local_addr().unwrap().port(),
        &"0".repeat(64),
        "sleep 30",
    );
    fs::create_dir(&options.cache).unwrap();
    fs::set_permissions(&options.cache, fs::Permissions::from_mode(0o700)).unwrap();
    let token = CancellationToken::new();
    let cancel = token.clone();
    let cancellation = tokio::spawn(async move {
        tokio::time::sleep(Duration::from_millis(100)).await;
        cancel.cancel();
    });
    let result = tokio::time::timeout(Duration::from_secs(3), pub_get::run(&options, token))
        .await
        .unwrap();
    assert_eq!(result.unwrap_err(), Error::Cancelled);
    assert!(log.exists());
    cancellation.await.unwrap();
}
